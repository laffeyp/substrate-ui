"""Generate web/vm/envelope_kinds.gen.ts from the kernel (Sprint 096).

The client used to hand-copy envelope kind strings (`web/vm/kinds.ts`); the copy drifted
(`"RunFinalised"` for the kernel's `"substrate.RunFinalised"`, Sep 23 to Oct 1) and the client
handled a kind no producer emits (`RateLimitedWaiting`). Hunt & Thomas, DRY: one authoritative
representation. The authority is the kernel's own registration of the session topology, read
through its public TopologyBuilder:

  - every schema a Producer kind registers (what Producers can emit),
  - every kind a Trigger or View subscribes to (what can be injected: UserMessage, ...),
  - every kind a topology injects without registering it (`tool_loop.INJECTED_EVENT_KINDS`),
  - the same for a driven session (a run's), and the run start written into a caller's record,
  - every `substrate.*` lifecycle kind in `substrate.api.LIFECYCLE_KINDS`,
  - the turn-end kinds and the kinds older session records carry (vocabulary § K.3).

Usage (source mode, from substrate-ui/):
  uv run --project ../substrate python scripts/gen_kinds.py          # write the file
  uv run --project ../substrate python scripts/gen_kinds.py --check  # exit 1 if stale
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "web" / "vm" / "envelope_kinds.gen.ts"
# UI sprint 107: the kernel's status enums, which the client retyped as string-literal unions.
STATUS_OUT = Path(__file__).resolve().parent.parent / "web" / "vm" / "statuses.gen.ts"
# Kernel K296 / UI sprint 143: the Length and Tone positions and their defaults (vocabulary § T).
CONTROLS_OUT = Path(__file__).resolve().parent.parent / "web" / "vm" / "controls.gen.ts"
# Kernel K312 / UI sprint 168: the language measure catalog, the watched measures and the intents.
LANGUAGE_OUT = Path(__file__).resolve().parent.parent / "web" / "vm" / "language_measures.gen.ts"


def session_kinds() -> set[str]:
    import warnings

    from substrate import api
    from substrate.adapters.models import DeterministicResponder
    from substrate.topologies.session import session_topology
    from substrate.topologies.session.vocabulary import LEGACY_SESSION_KINDS, TURN_END_KINDS
    from substrate.topologies.tool_loop import INJECTED_EVENT_KINDS

    from substrate.topologies.runs.card import read_card
    from substrate.topologies.runs.driven import DrivenRun
    from substrate.topologies.session.vocabulary import TOPOLOGY_RUN_STARTED, RunLimits

    # Vocabulary v0.12 (§ X): a run's session is driven, and registers the card, checks and report
    # kinds a person's session does not; a pane shows both.
    driven = DrivenRun(
        card=read_card(
            what="x", where=["x"], commands=["true"], statements=[], limits=RunLimits(1, 1)
        ),
        worktree=Path("/nonexistent"),
        base="",
        check_timeout_s=1,
        first_message="",
    )
    kinds: set[str] = set()
    for run in (None, driven):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # record_root=None warning: no run happens here
            topo = session_topology(
                driver=DeterministicResponder(0),
                driver_name="deterministic",
                driver_context_tokens=32768,
                seed="",
                tools={},
                session_id="s_generator",
                workspace_path="/nonexistent",
                bundle="session",
                language=True,  # vocabulary v0.11 (§ W): LanguageProfile, LanguageDrift
                driven=run,
            )
        b = api.TopologyBuilder()
        topo(b)
        reg = b.build()
        for pk in reg.producer_kinds.values():
            kinds.update(pk.schemas.keys())
        for t in reg.triggers:
            kinds.update(t.subscription.kinds)
        for v in reg.views.values():
            kinds.update(getattr(v.subscription, "kinds", ()) or ())
    # The run table writes a run's start into its caller's record (K319); nothing registers it.
    kinds.add(TOPOLOGY_RUN_STARTED)
    kinds.update(t.__name__ for t in INJECTED_EVENT_KINDS)
    kinds.update(api.LIFECYCLE_KINDS)
    # K260/U119: what a session record can end a turn with, and what older records carry.
    kinds.update(TURN_END_KINDS | LEGACY_SESSION_KINDS)
    return kinds


def render(kinds: set[str]) -> str:
    def key(k: str) -> str:
        return k.removeprefix("substrate.")

    keys = sorted(kinds, key=key)
    clash = {key(k) for k in keys if sum(1 for o in keys if key(o) == key(k)) > 1}
    if clash:
        raise SystemExit(
            f"gen_kinds: kind names collide once the substrate. prefix is dropped: {sorted(clash)}"
        )
    lines = [
        "// GENERATED by scripts/gen_kinds.py from the kernel's session-topology registration.",
        "// Do not edit. Regenerate: uv run --project ../substrate python scripts/gen_kinds.py",
        "// tests/test_envelope_kinds_generated_096.py fails when this file is stale.",
        "",
        "/* eslint-disable no-restricted-syntax */",
        "export const EnvelopeKind = {",
        *[f'  {key(k)}: "{k}",' for k in keys],
        "} as const;",
        "",
        "export type EnvelopeKindValue = typeof EnvelopeKind[keyof typeof EnvelopeKind];",
        "",
    ]
    return "\n".join(lines)


def render_statuses() -> str:
    """`SessionStatus` (a session manifest's status) and `TaskStatus` (a bash background task's),
    as `const` objects plus their value types."""
    from substrate.app import SessionStatus
    from substrate.topologies.tool_loop.background import TaskStatus

    lines = [
        "// GENERATED by scripts/gen_kinds.py from the kernel's status enums.",
        "// Do not edit. Regenerate: uv run --project ../substrate python scripts/gen_kinds.py",
        "// tests/test_envelope_kinds_generated_096.py fails when this file is stale.",
        "",
    ]
    for enum in (SessionStatus, TaskStatus):
        name = enum.__name__
        lines += [
            f"export const {name} = {{",
            *[f'  {m.name}: "{m.value}",' for m in enum],
            "} as const;",
            "",
            f"export type {name}Value = typeof {name}[keyof typeof {name}];",
            "",
        ]
    return "\n".join(lines)


def render_controls() -> str:
    """`LengthPosition` and `TonePosition` (session vocabulary § T) as `const` objects, each
    control's default, and the guidance levels with their bundles (§ R.1), so the workspace bar
    and the slash commands offer exactly what the daemon accepts."""
    from substrate.topologies.session.model_class import LEVEL_BUNDLES
    from substrate.topologies.session.vocabulary import (
        LENGTH_DEFAULT,
        TONE_DEFAULT,
        LengthPosition,
        TonePosition,
    )

    lines = [
        "// GENERATED by scripts/gen_kinds.py from the kernel's session vocabulary (§ T).",
        "// Do not edit. Regenerate: uv run --project ../substrate python scripts/gen_kinds.py",
        "// tests/test_envelope_kinds_generated_096.py fails when this file is stale.",
        "",
    ]
    for enum, default in ((LengthPosition, LENGTH_DEFAULT), (TonePosition, TONE_DEFAULT)):
        name = enum.__name__
        lines += [
            f"export const {name} = {{",
            *[f'  {m.name}: "{m.value}",' for m in enum],
            "} as const;",
            "",
            f"export type {name}Value = typeof {name}[keyof typeof {name}];",
            "",
        ]
    lines += [
        f"export const LENGTH_DEFAULT = LengthPosition.{LENGTH_DEFAULT.name};",
        f"export const TONE_DEFAULT = TonePosition.{TONE_DEFAULT.name};",
        "",
        # UI sprint 161 (§ R.1, § U): each guidance level and the bundle that carries it.
        "export const GUIDANCE_LEVEL_BUNDLES = {",
        *[f'  "{level.value}": "{bundle}",' for level, bundle in LEVEL_BUNDLES.items()],
        "} as const;",
        "",
        "export type GuidanceLevelValue = keyof typeof GUIDANCE_LEVEL_BUNDLES;",
        "",
    ]
    return "\n".join(lines)


def render_language_measures() -> str:
    """The kernel's language catalog (`substrate.app.language_catalog`): each measure's short name,
    unit, family, group, display range and explanation; the 13 watched measures in the detector's
    order; and the length and tone intents (`vocabulary.LANGUAGE_INTENTS`)."""
    import json

    from substrate.app import language_catalog, language_drift
    from substrate.topologies.session.vocabulary import LANGUAGE_INTENTS

    q = json.dumps
    lines = [
        "// GENERATED by scripts/gen_kinds.py from the kernel's language catalog (K312).",
        "// Do not edit. Regenerate: uv run --project ../substrate python scripts/gen_kinds.py",
        "// tests/test_envelope_kinds_generated_096.py fails when this file is stale.",
        "",
        "export const LanguageGroup = {",
        *[f"  {g.name}: {q(g.value)}," for g in language_catalog.Group],
        "} as const;",
        "",
        "export type LanguageGroupValue = typeof LanguageGroup[keyof typeof LanguageGroup];",
        "",
        "export interface LanguageMeasure {",
        "  short: string; unit: string; family: string; group: LanguageGroupValue;",
        "  low: number; high: number; explanation: string; count: boolean;",
        "}",
        "",
        "export const LANGUAGE_MEASURES: Record<string, LanguageMeasure> = {",
    ]
    for m in language_catalog.CATALOG.values():
        lines.append(
            f"  {q(m.name)}: {{ short: {q(m.short)}, unit: {q(m.unit)}, family: {q(m.family.value)}, "
            f"group: {q(m.group.value)}, low: {m.low:g}, high: {m.high:g}, "
            f"explanation: {q(m.explanation, ensure_ascii=False)}, count: {str(m.count).lower()} }},"
        )
    lines += [
        "};",
        "",
        "// The measures the live drift detector watches, in its order.",
        f"export const LANGUAGE_WATCHED = {q(list(language_drift.WATCHED))} as const;",
        f"export const LANGUAGE_WARMUP = {language_drift.DEFAULT_DRIFT.warmup};",
        "// The relation measures the turns stream shows, in order.",
        f"export const LANGUAGE_RELATION_LANES = {q(list(language_catalog.RELATION_LANES))} as const;",
        "// The words each side's window needs before style match is measured.",
        f"export const LANGUAGE_LSM_MIN_WORDS = {language_catalog.LSM_MIN_WORDS};",
        "",
        "// control -> position -> [measure, direction]: what each length and tone text states.",
        "export const LANGUAGE_INTENTS: Record<string, Record<string, [string, string][]>> = {",
    ]
    by_control: dict[str, dict[str, list[list[str]]]] = {}
    for (control, position), intents in LANGUAGE_INTENTS.items():
        by_control.setdefault(str(control), {})[str(position)] = [[m, str(d)] for m, d in intents]
    for control, positions in by_control.items():
        lines.append(f"  {q(control)}: {{")
        for position, pairs in positions.items():
            lines.append(f"    {q(position)}: {q(pairs)},")
        lines.append("  },")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    outputs = {
        OUT: render(session_kinds()),
        STATUS_OUT: render_statuses(),
        CONTROLS_OUT: render_controls(),
        LANGUAGE_OUT: render_language_measures(),
    }
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            sys.stderr.write(f"gen_kinds: {p} is stale; regenerate it\n")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text)
        print(f"gen_kinds: wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
