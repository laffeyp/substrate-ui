"""Generate the vocabulary's names and payload types from web/vm/signals/versions/current.json.

The tag names and enum values are written in current.json and nowhere else; the code names them
through these files (sprint 363):

  web/vm/signals.gen.ts, electron/signals.gen.ts  `Signal` and one string enum per enum field,
                                                   `SignalPayloads` (each tag's payload type)
  signals_gen.py                                   `Signal` and one StrEnum per enum field

Usage, from substrate-ui/:
  python3 scripts/gen_signals.py          # write the files
  python3 scripts/gen_signals.py --check  # exit 1 if any is stale
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOCAB = ROOT / "web" / "vm" / "signals" / "versions" / "current.json"
TS_OUTS = [ROOT / "web" / "vm" / "signals.gen.ts", ROOT / "electron" / "signals.gen.ts"]
PY_OUT = ROOT / "signals_gen.py"

HEADER = "SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0\nCopyright (C) 2026 Peter Laffey"
NOTE = (
    "GENERATED by scripts/gen_signals.py from web/vm/signals/versions/current.json. Do not edit.\n"
    "Regenerate: python3 scripts/gen_signals.py. tests/test_signals_generated.py fails when stale."
)


def pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in s.lower().split("_"))


def parse_type(spec: str) -> tuple[str, list[str], bool]:
    """(base, enum values, nullable) from a field type such as "enum a | b or null (note)"."""
    t = re.sub(r"\s*\([^)]*\)", "", spec).strip()
    nullable = t.endswith(" or null")
    if nullable:
        t = t[: -len(" or null")].strip()
    if t.startswith("enum "):
        return "enum", [x.strip() for x in t[5:].split("|")], nullable
    if t.startswith("list"):
        return "list", [], nullable
    return t, [], nullable


def load() -> dict:
    return json.loads(VOCAB.read_text())


def live_tags(vocab: dict) -> list[dict]:
    return [t for t in vocab["tags"] if not t.get("retired")]


def enum_fields(vocab: dict) -> list[tuple[dict, str, list[str]]]:
    out = []
    for t in live_tags(vocab):
        for f, spec in t.get("field_types", {}).items():
            base, values, _ = parse_type(spec)
            if base == "enum":
                out.append((t, f, values))
    return out


TS_BASE = {
    "int": "number",
    "float": "number",
    "string": "string",
    "bool": "boolean",
    "object": "Record<string, unknown>",
    "list": "unknown[]",
}


def render_ts(vocab: dict) -> str:
    q = json.dumps
    lines = [*("// " + h for h in HEADER.splitlines()), *("// " + n for n in NOTE.splitlines()), ""]
    lines.append(f"export const VOCAB_VERSION = {q(vocab['vocabulary_version'])};")
    # String enums: a plain string is not assignable to a member, so a raw tag or value fails tsc.
    lines += ["", "export enum Signal {"]
    lines += [f"  {t['name']} = {q(t['name'])}," for t in live_tags(vocab)]
    lines += ["}", ""]
    for t, f, values in enum_fields(vocab):
        lines.append(f"export enum {pascal(t['name']) + pascal(f)} {{")
        lines += [f"  {v.upper()} = {q(v)}," for v in values]
        lines += ["}", ""]
    lines.append("export interface SignalPayloads {")
    for t in live_tags(vocab):
        types = t.get("field_types", {})
        fields = []
        for f in [*t["payload"], *t.get("optional_payload", [])]:
            base, _, nullable = parse_type(types.get(f, "object"))
            ts = pascal(t["name"]) + pascal(f) if base == "enum" else TS_BASE[base]
            opt = "?" if f in t.get("optional_payload", []) else ""
            fields.append(f"{f}{opt}: {ts}{' | null' if nullable else ''}")
        lines.append(
            f"  [Signal.{t['name']}]: {{ {'; '.join(fields)} }};"
            if fields
            else f"  [Signal.{t['name']}]: Record<string, never>;"
        )
    lines += ["}", ""]
    return "\n".join(lines)


def render_py(vocab: dict) -> str:
    q = json.dumps
    lines = [
        *("# " + h for h in HEADER.splitlines()),
        '"""' + NOTE + '"""',
        "",
        "from enum import StrEnum",
        "",
        f"VOCAB_VERSION = {q(vocab['vocabulary_version'])}",
        "",
        "",
        "class Signal(StrEnum):",
    ]
    lines += [f"    {t['name']} = {q(t['name'])}" for t in live_tags(vocab)]
    for t, f, values in enum_fields(vocab):
        lines += ["", "", f"class {pascal(t['name']) + pascal(f)}(StrEnum):"]
        lines += [f"    {v.upper()} = {q(v)}" for v in values]
    lines.append("")
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    vocab = load()
    ts = render_ts(vocab)
    return {**{p: ts for p in TS_OUTS}, PY_OUT: render_py(vocab)}


def main() -> int:
    outs = outputs()
    if "--check" in sys.argv:
        stale = [p for p, text in outs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            sys.stderr.write(f"gen_signals: {p} is stale; run python3 scripts/gen_signals.py\n")
        return 1 if stale else 0
    for p, text in outs.items():
        p.write_text(text)
        print(f"gen_signals: wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
